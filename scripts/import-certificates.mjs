import { readdir, mkdir, copyFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import convert from "heic-convert";
import { readFile } from "node:fs/promises";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const SRC = "C:\\Users\\mufid\\Downloads\\Certificates-20260907T185623Z-1-001\\Certificates";
const DEST = path.join(root, "public", "certificates");

function slugify(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function titleFromFilename(filename) {
  const noExt = filename.replace(/\.[^.]+$/, "");
  return noExt.replace(/\.+$/, "").replace(/_/g, " ").trim();
}

async function isHeic(filePath) {
  const buf = await readFile(filePath);
  // HEIC files are ISO-BMFF: bytes 4-11 spell "ftyp" then a brand like "heic"/"mif1"/"heix"
  if (buf.length < 12) return false;
  const ftyp = buf.toString("ascii", 4, 8);
  const brand = buf.toString("ascii", 8, 12);
  return ftyp === "ftyp" && /^(heic|heix|mif1|heim|heis|hevc)/i.test(brand);
}

async function main() {
  await mkdir(DEST, { recursive: true });
  const categories = (await readdir(SRC, { withFileTypes: true })).filter((d) => d.isDirectory());

  const manifest = [];

  for (const catDir of categories) {
    const catName = catDir.name;
    const catSlug = slugify(catName);
    const srcCatPath = path.join(SRC, catName);
    const destCatPath = path.join(DEST, catSlug);
    await mkdir(destCatPath, { recursive: true });

    const files = (await readdir(srcCatPath, { withFileTypes: true })).filter((f) => f.isFile());

    for (const file of files) {
      const srcFilePath = path.join(srcCatPath, file.name);
      let outName = file.name;
      let ext = path.extname(file.name).toLowerCase();
      let type = ext === ".pdf" ? "pdf" : "image";

      const heic = await isHeic(srcFilePath);

      if (heic || ext === "") {
        // Convert HEIC (or extension-less HEIC) to JPEG.
        const inputBuffer = await readFile(srcFilePath);
        const outputBuffer = await convert({ buffer: inputBuffer, format: "JPEG", quality: 0.92 });
        outName = titleFromFilename(file.name) + ".jpg";
        const destFilePath = path.join(destCatPath, outName);
        await writeFile(destFilePath, outputBuffer);
        ext = ".jpg";
        type = "image";
      } else {
        const destFilePath = path.join(destCatPath, file.name);
        await copyFile(srcFilePath, destFilePath);
      }

      const title = titleFromFilename(file.name);
      // Use encodeURI, not encodeURIComponent: Vite's dev static server matches
      // file paths using encodeURI's escaping rules (it leaves & , + ; = @ $ ( ) !
      // unescaped), so encodeURIComponent-escaped punctuation 404s and falls
      // through to the SPA's index.html.
      const urlPath = `/certificates/${catSlug}/${encodeURI(outName)}`;

      manifest.push({
        title,
        category: catName,
        categorySlug: catSlug,
        fileName: outName,
        type,
        url: urlPath,
      });
    }
  }

  manifest.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

  const outFile = path.join(root, "src", "content", "certificateFiles.generated.ts");
  const body = `// Auto-generated by scripts/import-certificates.mjs — do not hand-edit.\nexport interface CertificateFile {\n  title: string;\n  category: string;\n  categorySlug: string;\n  fileName: string;\n  type: "pdf" | "image";\n  url: string;\n}\n\nexport const certificateFiles: CertificateFile[] = ${JSON.stringify(manifest, null, 2)};\n`;
  await writeFile(outFile, body);

  console.log(`Imported ${manifest.length} certificates across ${categories.length} categories.`);
  for (const cat of categories) {
    const count = manifest.filter((m) => m.category === cat.name).length;
    console.log(`  ${cat.name}: ${count}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
